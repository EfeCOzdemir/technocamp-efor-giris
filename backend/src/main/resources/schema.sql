CREATE TABLE APP_USER (
    ID        NUMBER(38, 0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME  VARCHAR2(100) NOT NULL UNIQUE,
    PASSWORD  VARCHAR2(100) NOT NULL,
    ROLE      VARCHAR2(20)  NOT NULL,
    AGENTID   VARCHAR2(100) NOT NULL UNIQUE,
    FIRSTNAME VARCHAR2(100) NOT NULL,
    SURNAME   VARCHAR2(100) NOT NULL
);

CREATE TABLE PERFORMANCE (
    ID          NUMBER(38, 0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    AGENTID     VARCHAR2(100),
    FIRSTNAME   VARCHAR2(100),
    SURNAME     VARCHAR2(100),
    "BEGIN"     TIMESTAMP,
    "END"       TIMESTAMP,
    DATEINFO    DATE,
    EXCUSE      VARCHAR2(100),
    EXCUSEHOURS NUMBER(38, 0),
    TIMEOUT     NUMBER(38, 0)
);

CREATE INDEX IX_PERFORMANCE_AGENT_DATE ON PERFORMANCE (AGENTID, DATEINFO);
